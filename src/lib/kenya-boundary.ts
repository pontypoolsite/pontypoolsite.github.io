function isOnSegment(
  longitude: number,
  latitude: number,
  [startLongitude, startLatitude]: Coordinate,
  [endLongitude, endLatitude]: Coordinate,
): boolean {
  const deltaLongitude = endLongitude - startLongitude;
  const deltaLatitude = endLatitude - startLatitude;
  const lengthSquared = deltaLongitude ** 2 + deltaLatitude ** 2;
  if (lengthSquared <= 1e-18) {
    return (longitude - startLongitude) ** 2 + (latitude - startLatitude) ** 2 <= 1e-18;
  }

  const cross = (longitude - startLongitude) * deltaLatitude
    - (latitude - startLatitude) * deltaLongitude;
  if (Math.abs(cross) > 1e-9) return false;

  const dot = (longitude - startLongitude) * deltaLongitude
    + (latitude - startLatitude) * deltaLatitude;
  return dot >= -1e-9 && dot <= lengthSquared + 1e-9;
}

function isInsideRing(longitude: number, latitude: number, ring: readonly Coordinate[]): boolean {
  let inside = false;

  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index, index += 1) {
    const [currentLongitude, currentLatitude] = ring[index];
    const [previousLongitude, previousLatitude] = ring[previous];

    if (isOnSegment(longitude, latitude, ring[previous], ring[index])) return true;

    const crossesLatitude = (currentLatitude > latitude) !== (previousLatitude > latitude);
    if (crossesLatitude) {
      const crossingLongitude = ((previousLongitude - currentLongitude)
        * (latitude - currentLatitude)) / (previousLatitude - currentLatitude) + currentLongitude;
      if (longitude < crossingLongitude) inside = !inside;
    }
  }

  return inside;
}

function isInCoastalCommunity(latitude: number, longitude: number): boolean {
  return coastalCommunities.some((community) => {
    const longitudeDistance = (longitude - community.longitude)
      * 111.32 * Math.cos(community.latitude * Math.PI / 180);
    const latitudeDistance = (latitude - community.latitude) * 111.32;
    return Math.hypot(longitudeDistance, latitudeDistance) <= community.radiusKm;
  });
}

export function isPointInKenya(latitude: number, longitude: number): boolean {
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)
    || latitude < -4.9 || latitude > 5.2 || longitude < 33.7 || longitude > 42.2) {
    return false;
  }

  return isInCoastalCommunity(latitude, longitude)
    || boundaryRings.some((ring) => isInsideRing(longitude, latitude, ring));
}
