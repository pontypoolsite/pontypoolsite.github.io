CREATE TABLE IF NOT EXISTS storefront_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id UUID NOT NULL UNIQUE,
  customer_name TEXT NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 200),
  email TEXT,
  phone TEXT,
  location TEXT NOT NULL CHECK (char_length(location) BETWEEN 1 AND 1000),
  location_latitude DOUBLE PRECISION,
  location_longitude DOUBLE PRECISION,
  delivery_method TEXT NOT NULL CHECK (delivery_method IN ('standard', 'express')),
  preferred_delivery_date DATE NOT NULL,
  preferred_delivery_time TEXT NOT NULL CHECK (
    preferred_delivery_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
  ),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'declined')),
  total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (email IS NOT NULL OR phone IS NOT NULL),
  CHECK (
    (location_latitude IS NULL AND location_longitude IS NULL)
    OR (
      location_latitude IS NOT NULL
      AND location_longitude IS NOT NULL
      AND location_latitude BETWEEN -4.9 AND 5.2
      AND location_longitude BETWEEN 33.7 AND 42.2
    )
  )
);

ALTER TABLE storefront_orders
  ADD COLUMN IF NOT EXISTS location_latitude DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS location_longitude DOUBLE PRECISION;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'storefront_orders_location_coordinates_check'
      AND conrelid = 'storefront_orders'::regclass
  ) THEN
    ALTER TABLE storefront_orders
      ADD CONSTRAINT storefront_orders_location_coordinates_check
      CHECK (
        (location_latitude IS NULL AND location_longitude IS NULL)
        OR (
          location_latitude IS NOT NULL
          AND location_longitude IS NOT NULL
          AND location_latitude BETWEEN -4.9 AND 5.2
          AND location_longitude BETWEEN 33.7 AND 42.2
        )
      );
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS storefront_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES storefront_orders(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL,
  variant_index INTEGER CHECK (variant_index IS NULL OR variant_index >= 0),
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
  line_total NUMERIC(12, 2) NOT NULL CHECK (line_total > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS storefront_orders_created_at_idx
  ON storefront_orders (created_at DESC);
CREATE INDEX IF NOT EXISTS storefront_orders_status_created_at_idx
  ON storefront_orders (status, created_at DESC);
CREATE INDEX IF NOT EXISTS storefront_order_items_order_id_idx
  ON storefront_order_items (order_id);

GRANT SELECT, INSERT, UPDATE ON TABLE storefront_orders TO storefront_app;
GRANT SELECT, INSERT ON TABLE storefront_order_items TO storefront_app;
GRANT USAGE, SELECT ON SEQUENCE
  public.storefront_orders_id_seq,
  public.storefront_order_items_id_seq
  TO storefront_app;
